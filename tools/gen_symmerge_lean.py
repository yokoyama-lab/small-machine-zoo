def aux_names(R):
    """FinalSymMergeBook・FinalSymMergeBlank・FinalSymMergeMoritaCount の最終定理（1 台ぶん）。"""
    n = R.name
    return [f"URTM.Univ.FinalSymMergeBook.exists_urtm_{n}_book", f"URTM.Univ.FinalSymMergeBook.book_urtm_{n}",
            f"URTM.Univ.FinalSymMergeBlank.blank_book_{n}", f"URTM.Univ.FinalSymMergeBlank.exists_urtm_{n}_blank",
            f"URTM.Univ.FinalSymMergeBlank.blank_desc_{n}", f"URTM.Univ.FinalSymMergeMoritaCount.count_book_{n}",
            f"URTM.Univ.FinalSymMergeMoritaCount.exists_urtm_{n}_moritaCount",
            f"URTM.Univ.FinalSymMergeMoritaCount.count_desc_{n}"]


def names(rs, kind):
    if kind == "univ":
        return [f"URTM.Univ.FinalSymMerge.exists_urtm_{R.name}" for R in rs] + [x for R in rs for x in aux_names(R)]
    if kind == "zoo":
        return [f"URTM.CTSH.SM{R.name}.blocks_simulates_ctsh" for R in rs]
    if kind == "axioms":
        return [x for R in rs for x in (f"URTM.Univ.SymMerge{R.name}.isUTMStrict_U",
                                         f"URTM.Univ.FinalSymMerge.exists_urtm_{R.name}")] + \
            [x for R in rs for x in [f"URTM.Univ.SymMergeBook{R.name}.isUTMStrict_B"] + aux_names(R)]
    raise SystemExit(f"unknown kind {kind}")


def axioms_block(rs):
    return "\n".join([MARK_BEGIN] + [f"#print axioms {x}" for x in names(rs, "axioms")] + [MARK_END])


def axioms_file(rs, text):
    if MARK_BEGIN in text:
        a = text.index(MARK_BEGIN)
        b = text.index(MARK_END, a) + len(MARK_END)
        return text[:a] + axioms_block(rs) + text[b:]
    return text.rstrip("\n") + "\n" + axioms_block(rs) + "\n"


def outputs(rs):
    """(パス, 文面) の列。KB の生成モジュールを含む。"""
    out = []
    for R in rs:
        out.append((f"lean/URTM/Gen/KB{R.name}.lean", kb_text(R)))
        out.append((f"lean/URTM/CTSH{R.name}Main.lean", zoo_text(R)))
        out.append((f"lean-univ/LeanUniv/SymMerge{R.name}.lean", univ_text(R)))
        out.append((f"lean-univ/LeanUniv/SymMergeBook{R.name}.lean", book_text(R)))
    out.append(("lean/URTM/SymMergeAll.lean", zoo_all_text(rs)))
    out.append(("lean-univ/LeanUniv/FinalSymMerge.lean", final_text(rs)))
    out.append(("lean-univ/LeanUniv/FinalSymMergeBook.lean", final_book_text(rs)))
    out.append(("lean-univ/LeanUniv/FinalSymMergeBlank.lean", final_blank_text(rs)))
    out.append(("lean-univ/LeanUniv/FinalSymMergeMoritaCount.lean", final_morita_text(rs)))
    ax = os.path.join(ROOT, "lean-univ/tests/Axioms.lean")
    out.append(("lean-univ/tests/Axioms.lean", axioms_file(rs, open(ax, encoding="utf-8").read())))
    return out


def guard(rel):
    """生成物でない既存のファイルを上書きしない。"""
    p = os.path.join(ROOT, rel)
    if os.path.exists(p) and "/Gen/" not in rel and not rel.endswith("Axioms.lean"):
        if GEN_NOTE not in open(p, encoding="utf-8").read():
            raise SystemExit(f"FAIL: {rel} exists and was not generated by {GEN_NOTE}")


def verify_all(rs, quiet=False):
    bad = 0
    for R in rs:
        errs = verify(R)
        if errs:
            bad += 1
            print(f"FAIL: {R.stem}: " + "; ".join(errs[:5]))
        elif not quiet:
            cl = R.classes()
            print(f"ok: {R.stem}: {R.raw} → {R.m} symbols, {len(cl)} classes, h = {R.pairs()}")
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default=None,
                    help=f"directory with records/ and merges/ (default {RESULTS}); for tests on a copy")
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("derive")
    d.add_argument("records", nargs="+")
    d.add_argument("--force", action="store_true")
    sub.add_parser("verify")
    sub.add_parser("write")
    sub.add_parser("check")
    sub.add_parser("kb")
    nm = sub.add_parser("names")
    nm.add_argument("kind", choices=["univ", "zoo", "axioms"])
    a = ap.parse_args()
    if a.cmd == "derive":
        for p in a.records:
            R = Rec(os.path.abspath(p))
            print(f"{R.stem}: {derive(R, a.force)} symbols → {os.path.relpath(R.mpath, ROOT)}")
        return 0
    rs = records(a.results)
    if a.cmd == "names":
        print("\n".join(names(rs, a.kind)))
        return 0
    if a.cmd == "kb":
        for R in rs:
            with open(os.path.join(ROOT, f"lean/URTM/Gen/KB{R.name}.lean"), "w") as f:
                f.write(kb_text(R))
            print(f"KB{R.name}")
        return 0
    if a.cmd == "verify":
        return 1 if verify_all(rs) else 0
    if a.cmd == "write":
        if verify_all(rs):
            return 1
        for rel, text in outputs(rs):
            guard(rel)
            os.makedirs(os.path.dirname(os.path.join(ROOT, rel)), exist_ok=True)
            with open(os.path.join(ROOT, rel), "w", encoding="utf-8") as f:
                f.write(text)
            print(f"wrote {rel}")
        return 0
    if a.cmd == "check":
        bad = verify_all(rs, quiet=True)
        outs = outputs(rs)
        for rel, text in outs:
            p = os.path.join(ROOT, rel)
            if not os.path.exists(p) or open(p, encoding="utf-8").read() != text:
                print(f"FAIL: {rel} missing or differs from {GEN_NOTE} output")
                bad += 1
        stale = [p for pat in ("lean/URTM/CTSH*Main.lean", "lean-univ/LeanUniv/SymMerge[0-9]*.lean",
                               "lean-univ/LeanUniv/SymMergeBook[0-9]*.lean")
                 for p in glob.glob(os.path.join(ROOT, pat))
                 if GEN_NOTE in open(p, encoding="utf-8").read()
                 and os.path.relpath(p, ROOT) not in {rel for rel, _ in outs}]
        for p in stale:
            print(f"FAIL: {os.path.relpath(p, ROOT)} was generated for a record that is gone")
            bad += 1
        print(f"{len(rs)} records, {bad} problems")
        return 1 if bad else 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
