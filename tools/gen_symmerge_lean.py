def block_at(B):
    """BlockHalt.isUTMStrictHalt_block<..> に対応する SymMergeBook.isUTMStrictHaltAt_block<..>。"""
    assert B["block"].startswith("isUTMStrictHalt_block"), B["block"]
    return B["block"].replace("isUTMStrictHalt_", "isUTMStrictHaltAt_", 1)


class Rec:
    """1 台ぶんの記録: Python の表、Lean の番号付け、併合の写像。"""

    def __init__(self, path):
        self.path = path
        self.stem = os.path.basename(path)[:-len(".json")]
        m = STEM.match(self.stem)
        if not m:
            raise SystemExit(f"FAIL: record name {self.stem!r} is not urtm<m>-<n>.k<k>.r<raw>.m<merged>")
        self.k, self.raw, self.m = int(m.group(3)), int(m.group(4)), int(m.group(5))
        self.name = f"{self.k}_{self.m}"
        self.r = json.load(open(path))
        if self.r["machine"] not in BASES:
            raise SystemExit(f"FAIL: {self.stem}: base {self.r['machine']} is not supported (BASES)")
        self.B = BASES[self.r["machine"]]
        self.info = kstate_blocks.Info(kstate_blocks.machine_path(self.r["machine"]))
        self.T = self.info.T
        self.g = kstate_blocks.gen_of(self.info, self.r)
        if self.g.conflicts():
            raise SystemExit(f"FAIL: {self.stem}: the block table has conflicts {self.g.conflicts()[:2]}")
        if self.g.k != self.k or len(self.g.symbols) != self.raw:
            raise SystemExit(f"FAIL: {self.stem}: the table has {self.g.k} states / {len(self.g.symbols)} symbols")
        if len(self.T.symbols) != self.B["n"]:
            raise SystemExit(f"FAIL: {self.stem}: base has {len(self.T.symbols)} symbols, BASES says {self.B['n']}")
        self.mpath = os.path.join(os.path.dirname(os.path.dirname(path)), "merges", self.stem + ".json")

    # --- Lean の番号付け（BlockGen.numB: 状態 Fin k は値、疑似状態は k + 位置、pl s ↦ s の番号、
    #     ctr i s ↦ n·(i+1) + s の番号。基底の記号の番号は記述ファイルの symbols の位置） ---
    def plain(self, x):
        return not self.g.is_counter(x)

    def num(self, x):
        n = self.B["n"]
        if self.g.is_counter(x):
            i, s = self.g.split_counter(x)
            assert i >= 0, x
            return n * (i + 1) + self.T.symbols.index(s)
        return self.T.symbols.index(x)

    def stnum(self, q):
        if q in self.T.pseudo:
            return self.k + self.T.pseudo.index(q)
        return self.g.states.index(q)

    def classes(self):
        if not os.path.exists(self.mpath):
            raise SystemExit(f"FAIL: {self.stem}: no merge file {os.path.relpath(self.mpath, ROOT)} (run derive)")
        return json.load(open(self.mpath))["classes"]

    def rep(self):
        rep = {}
        for c in self.classes():
            for x in c:
                if x in rep:
                    raise SystemExit(f"FAIL: {self.stem}: symbol {x} in two classes")
                rep[x] = c[0]
        return rep

    def pairs(self):
        """Lean の h = symMap pairs（代表でない記号の番号 ↦ 代表の番号）。番号の順。"""
        rep = self.rep()
        return sorted((self.num(x), self.num(r)) for x, r in rep.items() if x != r)

    def numbered(self):
        """(UB, U): Lean の番号付けの五つ組の列（UB = numT (numB k) TpyB、U = mapQ h UB）。並びは TpyB のまま。"""
        UB = [(self.stnum(p), self.num(s), self.num(t), d, self.stnum(q)) for (p, s, t, d, q) in self.g.quints]
        h = dict(self.pairs())
        return UB, [(p, h.get(s, s), h.get(t, t), d, q) for (p, s, t, d, q) in UB]

    def merged(self):
        """Lean の U: mapQ h UB。併合で同じ規則になった五つ組があれば、Mathlib の List.dedup と同じく
        重なりの最後の 1 つだけを残す（pwFilter は右から畳むので後ろが残る）。"""
        _, U0 = self.numbered()
        if len(set(U0)) == len(U0):
            return U0
        seen, out = set(), []
        for r in reversed(U0):
            if r not in seen:
                seen.add(r)
                out.append(r)
        return out[::-1]

    def has_repeats(self):
        _, U0 = self.numbered()
        return len(set(U0)) != len(U0)

    def book(self):
        """(H, B): H = U のうち出ていく五つ組を持たない状態へ入る五つ組（U の並び。Lean の
        `U.filter (fun r => decide (r.q ∉ U.map Quint.p))`）、B = dropT U H。"""
        U = self.merged()
        src = {r[0] for r in U}
        H = [r for r in U if r[4] not in src]
        return H, [r for r in U if r not in H]


def run(delta, pseudo, blank, state, pos, tape, limit):
    tape = list(tape)
    for step in range(limit + 1):
        while pos >= len(tape):
            tape.append(blank)
        if pos < 0:
            return step, None, tape, "fell"
        r = delta.get((state, tape[pos]))
        if r is None:
            return step, (state, tape[pos]), tape, "stuck"
        t, d, q = r
        tape[pos] = t
        pos += {"-": -1, "0": 0, "+": 1}[d]
        state = q
        if q in pseudo:
            return step + 1, None, tape, q
    return limit, None, tape, "maxstep"


def test_runs(R, delta, recode=None):
    """試験例（基底の記述ファイルの initial_conf を符号化したもの）を走らせる。"""
    T, g = R.T, R.g
    maxstep = T.maxstep * (3 + 2 * max(1, g.nctr)) + 10
    out = []
    for (state, pos, tape, _s, _o) in T.cases:
        st, ps, tp = g.encode_conf(state, pos, tape)
        if recode:
            tp = [recode.get(x, x) for x in tp]
        out.append(run(delta, set(T.pseudo), T.blank, st, ps, tp, maxstep))
    return out


def conflict_sources(R):
    """衝突の出どころ: (reads, writes, finals)。reads[p] = 状態 p が読む記号（試験例で止まった (状態, 記号) を含む）、
    writes[q] = 状態 q へ入る五つ組が書く記号、finals = 試験例の停止時のテープに現れる記号の集合の列。"""
    reads, writes = defaultdict(set), defaultdict(set)
    for (p, s, t, d, q) in R.g.quints:
        reads[p].add(s)
        writes[q].add(t)
    delta = {(p, s): (t, d, q) for (p, s, t, d, q) in R.g.quints}
    finals = []
    for (_n, stuck, tape, why) in test_runs(R, delta):
        if stuck:
            reads[stuck[0]].add(stuck[1])
        if why in R.T.pseudo:
            finals.append(set(tape))
    return reads, writes, finals


def conflict_graph(R):
    """README（results/symmerge-2026-10-04）の衝突グラフ: 同じ状態が読む / 同じ状態へ書いて入る /
    試験例の停止時のテープに共に現れる。止まった (状態, 記号) も読むに数える。"""
    reads, writes, finals = conflict_sources(R)
    adj = {x: set() for x in R.g.symbols}
    for grp in list(reads.values()) + list(writes.values()) + finals:
        for x in grp:
            if x in adj:
                adj[x] |= (grp & adj.keys()) - {x}
    return adj


def class_conflicts(R, rep):
    """検算 1〜3: 同じ類の 2 記号の衝突のうち許されないもの（frozenset の集合）と、併合で 2 規則が同じ規則に
    なるので許した組の数。読む側は (p, x)・(p, y) の 2 規則、書く側は (q, x)・(q, y) へ書いて入る 2 規則の像が
    一致するときだけ許す（止まった (状態, 記号) は規則が無いので許さない）。停止時のテープは従来どおり。"""
    reads, writes, finals = conflict_sources(R)
    by_read = {(p, s): (p, s, t, d, q) for (p, s, t, d, q) in R.g.quints}
    by_write = {(q, t): (p, s, t, d, q) for (p, s, t, d, q) in R.g.quints}

    def img(r):
        return None if r is None else (r[0], rep.get(r[1], r[1]), rep.get(r[2], r[2]), r[3], r[4])

    bad, excused = set(), set()
    for src, idx in ((reads, by_read), (writes, by_write)):
        for st, grp in src.items():
            g = sorted(grp)
            for i, x in enumerate(g):
                for y in g[i + 1:]:
                    if rep.get(x, x) != rep.get(y, y):
                        continue
                    a, b = img(idx.get((st, x))), img(idx.get((st, y)))
                    if a is not None and a == b:
                        excused.add(frozenset((x, y)))
                    else:
                        bad.add(frozenset((x, y)))
    for grp in finals:
        g = sorted(grp & set(R.g.symbols))
        for i, x in enumerate(g):
            for y in g[i + 1:]:
                if rep.get(x, x) == rep.get(y, y):
                    bad.add(frozenset((x, y)))
    return bad, len(excused - bad)


def dsatur(nodes, adj, order_key):
    col, sat = {}, {v: set() for v in nodes}
    while len(col) < len(nodes):
        v = max((u for u in nodes if u not in col), key=lambda u: (len(sat[u]), len(adj[u]), order_key(u)))
        c = 0
        while c in sat[v]:
            c += 1
        col[v] = c
        for w in adj[v]:
            sat[w].add(c)
    return col


def derive(R, force=False):
    if os.path.exists(R.mpath) and not force:
        raise SystemExit(f"FAIL: {os.path.relpath(R.mpath, ROOT)} exists (use --force)")
    adj = conflict_graph(R)
    plains = [x for x in R.g.symbols if R.plain(x)]
    for x in plains:                       # 条件 4: 平の記号どうしは併合しない
        adj[x] |= set(plains) - {x}
    nodes = list(R.g.symbols)
    import random
    best = None
    for seed in range(200):
        rng = random.Random(seed)
        key = {x: rng.random() for x in nodes} if seed else {x: -R.num(x) for x in nodes}
        col = dsatur(nodes, adj, lambda u: key[u])
        ncol = len(set(col.values()))
        if best is None or ncol < best[0]:
            best = (ncol, col, seed)
        if ncol <= R.m:
            break
    ncol, col, seed = best
    if ncol != R.m:
        raise SystemExit(f"FAIL: {R.stem}: DSATUR reached {ncol} symbols, not the target {R.m}")
    cls = defaultdict(list)
    for x, c in col.items():
        cls[c].append(x)
    out = []
    for mem in cls.values():
        if len(mem) < 2:
            continue
        pl = [x for x in mem if R.plain(x)]
        rep = pl[0] if pl else min(mem, key=R.num)
        out.append([rep] + sorted((x for x in mem if x != rep), key=R.num))
    out.sort(key=lambda c: R.num(c[0]))
    os.makedirs(os.path.dirname(R.mpath), exist_ok=True)
    with open(R.mpath, "w") as f:
        json.dump({"record": R.stem + ".json", "classes": out, "nsyms": ncol,
                   "note": f"tools/gen_symmerge_lean.py derive (DSATUR, seed {seed})"}, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return ncol


def spec_counts(rules):
    """Spec の定義どおり: 決定性・可逆性・NStates・NSyms（空白 0 を数える）。rules は数の五つ組。"""
    rs = list(dict.fromkeys(rules))
    det = all(not (a[0] == b[0] and a[1] == b[1]) or a == b for a in rs for b in rs)
    rev = all(a == b or a[4] != b[4] or (a[3] == b[3] and a[2] != b[2]) for a in rs for b in rs)
    nst = len({r[0] for r in rules})
    nsy = len({0} | {r[1] for r in rules} | {r[2] for r in rules})
    return det, rev, nst, nsy


def verify(R):
    """検算。失敗の理由の列を返す（空なら合格）。"""
    errs = []
    classes = R.classes()
    rep = R.rep()
    syms = set(R.g.symbols)
    bad, _ = class_conflicts(R, rep)
    for c in classes:
        if len(c) < 2:
            errs.append(f"class {c} has fewer than 2 symbols")
        for x in c:
            if x not in syms:
                errs.append(f"{x} is not a symbol of the table")
        pl = [x for x in c if R.plain(x)]
        if len(pl) > 1:
            errs.append(f"class {c} has two plain symbols {pl}")
        if pl and c[0] != pl[0]:
            errs.append(f"class {c}: the representative is not the plain symbol {pl[0]}")
        for i, x in enumerate(c):
            for y in c[i + 1:]:
                if frozenset((x, y)) in bad:
                    errs.append(f"class {c}: {x} and {y} conflict")
    merged = {rep.get(x, x) for x in syms}
    if len(merged) != R.m:
        errs.append(f"merged table has {len(merged)} symbols, the name says {R.m}")
    # 試験例
    delta = {(p, s): (t, d, q) for (p, s, t, d, q) in R.g.quints}
    mq = {(p, rep.get(s, s), rep.get(t, t), d, q) for (p, s, t, d, q) in R.g.quints}
    mdelta = {}
    for (p, s, t, d, q) in mq:
        if (p, s) in mdelta:
            errs.append(f"merged table is not deterministic at {(p, s)}")
        mdelta[(p, s)] = (t, d, q)
    for (n1, s1, f1, k1), (n2, s2, f2, k2) in zip(test_runs(R, delta), test_runs(R, mdelta, rep)):
        img = [rep.get(x, x) for x in f1]
        while img and img[-1] == R.T.blank:
            img.pop()
        while f2 and f2[-1] == R.T.blank:
            f2.pop()
        if not (n1 == n2 and k1 == k2 and img == f2):
            errs.append(f"test case differs: {n1} {k1} vs {n2} {k2}")
        if k1 in ("stuck", "fell"):
            errs.append(f"test case of the unmerged table ends with {k1}")
    # Lean の番号付けで数える
    UB = [(R.stnum(p), R.num(s), R.num(t), d, R.stnum(q)) for (p, s, t, d, q) in R.g.quints]
    h = dict(R.pairs())
    U = [(p, h.get(s, s), h.get(t, t), d, q) for (p, s, t, d, q) in UB]
    detB, revB, nstB, nsyB = spec_counts(UB)
    det, rev, nst, nsy = spec_counts(U)
    if not (detB and revB and nstB == R.k and nsyB == R.raw):
        errs.append(f"numbered unmerged table: det={detB} rev={revB} NStates={nstB} NSyms={nsyB}")
