def final_blank_text(rs):
    L = [final_aux_header(
        "The blank occurs and the counts are not inflated", "FinalBlank",
        """
  * `blank_book_<k>_<m>`: some quintuple of `B` reads the blank 0, `(symbols B).dedup.length = NSyms B` (the
    blank that `NSyms` adds occurs in the table), every symbol of `B` is read by some quintuple and written
    by some quintuple, and `(states B).dedup.length = NStates B` (no target-only state).
  * `exists_urtm_<k>_<m>_blank`: these facts added to `exists_urtm_<k>_<m>_book`.
  * `blank_desc_<k>_<m>`: the first three for `U` (its two pseudo-states occur only as targets).
""")]
    L += [f"import LeanUniv.SymMergeBook{R.name}" for R in rs]
    L += ["", "namespace URTM.Univ.FinalSymMergeBlank", "open URTM"]
